"""Build relay-bridge.apk with the Android SDK command-line tools only (no Gradle).

    python android/bridge/build.py [--sdk D:/Android/Sdk] [--jdk <jdk 17>] [--out android/bridge/build]

Needs a JDK 17+, SDK build-tools (d8, aapt2, zipalign, apksigner) and one platform's android.jar
(android/toolchain.py finds them), and penrose's signing key (android/README.md). The Xposed API classes
under stubs/ are compiled against but not packaged: the framework (LSPosed/Vector) provides them at runtime.
`python android/build.py` builds it into desktop/assets/android with the rest.
"""

import argparse
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from toolchain import Tools, run  # noqa: E402

OUT = HERE / "build"
# One page script for both ways penrose reads a web page: Chrome's tabs over DevTools (backend/app/bridge/chrome.py)
# and an app's WebViews through this module (Web.java).
WEB_JS = HERE.parents[1] / "backend" / "app" / "bridge" / "web.js"


def java_literal(text: str) -> str:
    """`text` as the body of a Java string literal (ASCII only, so no source-encoding surprises)."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            continue
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) > 126:
            for unit in ch.encode("utf-16-be").hex(" ", 2).split():
                out.append("\\u" + unit)
        else:
            out.append(ch)
    return "".join(out)


def write_web_script(dest: Path):
    """backend/app/bridge/web.js as WebScript.SOURCE. A class-file string constant tops out at 64 KB, so the
    script goes in as chunks joined at class-load time."""
    source = WEB_JS.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip()
    chunks = [source[i:i + 12000] for i in range(0, len(source), 12000)]
    body = ",\n        ".join(f'"{java_literal(c)}"' for c in chunks)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        "package app.relay.bridge;\n\n"
        "/** Generated by build.py from web.js: the page script Web.java sends into WebViews. */\n"
        "final class WebScript {\n"
        f"    private static final String[] PARTS = {{\n        {body}\n    }};\n"
        '    static final String SOURCE = String.join("", PARTS);\n'
        "}\n",
        encoding="utf-8",
    )


def write_interceptor_dex(dex: Path, dest: Path):
    """shim/ (the OkHttp interceptor class, dexed on its own) as InterceptorDex.BASE64, which
    Module loads into the app's class loader next to its okhttp3 classes."""
    import base64
    encoded = base64.b64encode(dex.read_bytes()).decode("ascii")
    chunks = [encoded[i:i + 12000] for i in range(0, len(encoded), 12000)]
    body = ",\n        ".join(f'"{c}"' for c in chunks)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        "package app.relay.bridge;\n\n"
        "/** Generated by build.py from shim/: the dex holding app.relay.bridge.okhttp.RecorderInterceptor. */\n"
        "final class InterceptorDex {\n"
        f"    private static final String[] PARTS = {{\n        {body}\n    }};\n"
        '    static final String BASE64 = String.join("", PARTS);\n'
        "}\n",
        encoding="utf-8",
    )


def build(out: Path = OUT, tools: Tools | None = None) -> Path:
    tools = tools or Tools()
    out = Path(out).resolve()
    shutil.rmtree(out, ignore_errors=True)
    stub_classes, classes, dex = out / "stubs", out / "classes", out / "dex"
    for d in (stub_classes, classes, dex):
        d.mkdir(parents=True)

    java8 = tools.java8()
    run(tools.javac, *java8, "-d", stub_classes, *sorted((HERE / "stubs").rglob("*.java")))
    gen = out / "gen"
    write_web_script(gen / "app" / "relay" / "bridge" / "WebScript.java")
    # The OkHttp interceptor is compiled against the okhttp3 stubs and dexed apart from the
    # module: it lives in the app's class loader at runtime (see shim/RecorderInterceptor.java).
    shim_classes, shim_dex = out / "shim-classes", out / "shim-dex"
    shim_classes.mkdir()
    shim_dex.mkdir()
    run(tools.javac, *java8, "-cp", stub_classes, "-d", shim_classes, *sorted((HERE / "shim").rglob("*.java")))
    run(tools.tool("d8"), "--release", "--min-api", "30", "--lib", tools.android_jar, "--classpath", stub_classes,
        "--output", shim_dex, *sorted(shim_classes.rglob("*.class")))
    write_interceptor_dex(shim_dex / "classes.dex", gen / "app" / "relay" / "bridge" / "InterceptorDex.java")
    run(tools.javac, *java8, "-cp", stub_classes, "-d", classes,
        *sorted((HERE / "src").rglob("*.java")), *sorted(gen.rglob("*.java")))
    run(tools.tool("d8"), "--release", "--min-api", "30", "--lib", tools.android_jar, "--output", dex,
        *sorted(classes.rglob("*.class")))

    unsigned = out / "unsigned.apk"
    run(tools.tool("aapt2"), "link", "-o", unsigned, "--manifest", HERE / "AndroidManifest.xml",
        "-I", tools.android_jar, "-A", HERE / "assets")
    with zipfile.ZipFile(unsigned, "a") as apk:
        apk.write(dex / "classes.dex", "classes.dex")

    aligned = out / "aligned.apk"
    run(tools.tool("zipalign"), "-f", "-p", "4", unsigned, aligned)
    final = out / "relay-bridge.apk"
    tools.sign(aligned, final)
    print(f"\nBuilt {final}")
    return final


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sdk")
    parser.add_argument("--jdk")
    parser.add_argument("--out", default=str(OUT), help="build directory (default: ./build); wiped first")
    args = parser.parse_args()
    build(Path(args.out), Tools(args.sdk, args.jdk))


if __name__ == "__main__":
    main()
